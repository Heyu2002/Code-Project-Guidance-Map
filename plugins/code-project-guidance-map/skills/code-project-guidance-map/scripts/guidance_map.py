def find_block(text: str) -> tuple[int, int, str] | None:
    start_count = text.count(START_MARKER)
    end_count = text.count(END_MARKER)
    if start_count == 0 and end_count == 0:
        return None
    if start_count != 1 or end_count != 1:
        raise GuidanceMapError("Malformed guidance block markers: expected exactly one start and one end marker.")
    start = text.index(START_MARKER)
    end_marker_start = text.index(END_MARKER)
    if end_marker_start < start:
        raise GuidanceMapError("Malformed guidance block markers: end marker appears before start marker.")
    end = end_marker_start + len(END_MARKER)
    return start, end, text[start:end]


def metadata_value(pattern: re.Pattern[str], block: str | None) -> str | None:
    if not block:
        return None
    match = pattern.search(block)
    if not match:
        return None
    return match.group("value").strip()


def parse_iso_datetime(value: str | None) -> datetime | None:
    if not value:
        return None
    normalized = value.strip()
    if normalized.endswith("Z"):
        normalized = f"{normalized[:-1]}+00:00"
    try:
        parsed = datetime.fromisoformat(normalized)
    except ValueError:
        return None
    if parsed.tzinfo is None:
        parsed = parsed.replace(tzinfo=timezone.utc)
    return parsed.astimezone(timezone.utc)


def parse_semver(value: str | None) -> tuple[int, int, int] | None:
    if not value:
        return None
    match = re.fullmatch(r"(0|[1-9]\d*)\.(0|[1-9]\d*)\.(0|[1-9]\d*)", value.strip())
    if not match:
        return None
    return int(match.group(1)), int(match.group(2)), int(match.group(3))


def generator_version_status(version: str | None, current: str = GENERATOR_VERSION) -> str:
    parsed = parse_semver(version)
    current_parsed = parse_semver(current)
    if version is None:
        return "missing"
    if parsed is None or current_parsed is None:
        return "invalid"
    if parsed == current_parsed:
        return "current"
    if parsed[:2] == current_parsed[:2]:
        return "patch-compatible"
    return "incompatible"


def unique_ordered(values: Iterable[str]) -> list[str]:
    seen: set[str] = set()
    result: list[str] = []
    for value in values:
        value = value.strip().replace("\\", "/")
        if not value or value in seen:
            continue
        seen.add(value)
        result.append(value)
    return result


def matches_any(path: str, patterns: Iterable[str]) -> bool:
    normalized = path.strip().replace("\\", "/")
    return any(fnmatch.fnmatchcase(normalized, pattern) for pattern in patterns)


def is_generated_guidance_path(path: str) -> bool:
    return matches_any(path, GENERATED_GUIDANCE_PATTERNS)


def is_tool_ignored_change_path(path: str) -> bool:
    return matches_any(path, TOOL_IGNORED_CHANGE_PATTERNS)


def classify_changed_files(files: Iterable[str]) -> dict[str, list[str]]:
    impact = {
        "boundary_rules": [],
        "task_routing": [],
        "module_internal": [],
        "docs_only": [],
        "other": [],
    }
    for file in unique_ordered(files):
        if matches_any(file, BOUNDARY_SENSITIVE_PATTERNS):
            impact["boundary_rules"].append(file)
        elif matches_any(file, TASK_ROUTING_PATTERNS):
            impact["task_routing"].append(file)
        elif matches_any(file, DOCS_PATTERNS):
            impact["docs_only"].append(file)
        elif matches_any(file, CODE_PATTERNS):
            impact["module_internal"].append(file)
        else:
            impact["other"].append(file)
    return impact


def git_files(repo: Path, args: list[str]) -> list[str]:
    result = run_git(repo, args)
    if result.returncode != 0:
        return []
    return [line.strip() for line in result.stdout.splitlines() if line.strip()]


def file_content_state(repo: Path, relpath: str) -> str:
    path = (repo / relpath).resolve()
    try:
        path.relative_to(repo.resolve())
    except ValueError:
        return "outside"
    try:
        if not path.exists():
            return "missing"
        if not path.is_file():
            return "non-file"
        digest = hashlib.sha256(path.read_bytes()).hexdigest()
    except OSError:
        return "unreadable"
    return f"sha256:{digest}"


def encode_local_change_baseline(entries: dict[str, str]) -> str:
    normalized = [[path, entries[path]] for path in sorted(entries)]
    payload = json.dumps(normalized, ensure_ascii=False, separators=(",", ":")).encode("utf-8")
    encoded = base64.urlsafe_b64encode(payload).decode("ascii").rstrip("=")
    digest = hashlib.sha256(payload).hexdigest()
    return f"sha256:{digest}:{encoded}"


def decode_local_change_baseline(value: str | None) -> tuple[dict[str, str], bool]:
    if value is None:
        return {}, True
    pieces = value.strip().split(":", 2)
    if len(pieces) != 3 or pieces[0] != "sha256" or not re.fullmatch(r"[0-9a-f]{64}", pieces[1]):
        return {}, False
    encoded = pieces[2]
    try:
        padding = "=" * (-len(encoded) % 4)
        payload = base64.urlsafe_b64decode((encoded + padding).encode("ascii"))
        if hashlib.sha256(payload).hexdigest() != pieces[1]:
            return {}, False
        decoded = json.loads(payload.decode("utf-8"))
    except (OSError, ValueError, binascii.Error, json.JSONDecodeError):
        return {}, False
    if not isinstance(decoded, list):
        return {}, False
    entries: dict[str, str] = {}
    for item in decoded:
        if not (
            isinstance(item, list)
            and len(item) == 2
            and isinstance(item[0], str)
            and isinstance(item[1], str)
        ):
            return {}, False
        path = item[0].strip().replace("\\", "/")
        state = item[1].strip()
        if not path or path.startswith("../") or "/../" in path or path in {".", ".."}:
            return {}, False
        entries[path] = state
    return entries, True


def local_change_baseline(repo: Path, git_available: bool) -> str:
    if not git_available:
        return encode_local_change_baseline({})
    local_files = unique_ordered(
        [
            *git_files(repo, ["diff", "--name-only", "--cached"]),
            *git_files(repo, ["diff", "--name-only"]),
            *git_files(repo, ["ls-files", "--others", "--exclude-standard"]),
        ]
    )
    entries = {
        file: file_content_state(repo, file)
        for file in local_files
        if not is_generated_guidance_path(file) and not is_tool_ignored_change_path(file)
    }
    return encode_local_change_baseline(entries)


def baseline_ignored_files(repo: Path, files: Iterable[str], baseline: dict[str, str]) -> list[str]:
    ignored: list[str] = []
    for file in unique_ordered(files):
        expected = baseline.get(file)
        if expected is not None and file_content_state(repo, file) == expected:
            ignored.append(file)
    return ignored


def filter_baseline_ignored(files: Iterable[str], ignored: set[str]) -> list[str]:
    return [file for file in unique_ordered(files) if file not in ignored]


def tool_ignored_files(files: Iterable[str]) -> list[str]:
    return [file for file in unique_ordered(files) if is_tool_ignored_change_path(file)]


def changed_files(
    repo: Path,
    git_available: bool,
    since: datetime | None,
    baseline: dict[str, str] | None = None,
) -> dict[str, list[str]]:
    if not git_available:
        return {
            "committed": [],
            "staged": [],
            "unstaged": [],
            "untracked": [],
            "baseline_ignored": [],
            "tool_ignored": [],
            "all": [],
        }

    committed: list[str] = []
    if since is not None:
        since_arg = since.strftime("%Y-%m-%d %H:%M:%S %z")
        committed = git_files(repo, ["log", f"--since={since_arg}", "--name-only", "--pretty=format:"])

    staged = git_files(repo, ["diff", "--name-only", "--cached"])
    unstaged = git_files(repo, ["diff", "--name-only"])
    untracked = git_files(repo, ["ls-files", "--others", "--exclude-standard"])
    all_files = unique_ordered([*committed, *staged, *unstaged, *untracked])
    ignored_list = baseline_ignored_files(repo, all_files, baseline or {})
    tool_ignored_list = tool_ignored_files(all_files)
    ignored = {*ignored_list, *tool_ignored_list}

    return {
        "committed": filter_baseline_ignored(committed, ignored),
        "staged": filter_baseline_ignored(staged, ignored),
        "unstaged": filter_baseline_ignored(unstaged, ignored),
        "untracked": filter_baseline_ignored(untracked, ignored),
        "baseline_ignored": ignored_list,
        "tool_ignored": tool_ignored_list,
        "all": filter_baseline_ignored(all_files, ignored),
    }


